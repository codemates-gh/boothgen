#!/usr/bin/env node
// The production SQL check: docs/genie/check-production-sql.sql, a read-only Neon query that reports, for every
// docs/genie/apply-production-*.sql file, whether its tables and columns exist (applied / NOT RUN / PARTIAL; not-run
// files first). Generated from those files' ADD COLUMN and CREATE TABLE lines, so it never goes stale by hand.
//
//   node scripts/genie-sql-check.mjs            regenerates docs/genie/check-production-sql.sql
//   node scripts/genie-sql-check.mjs --check    exits 1 when the file is out of date (tests/genie/sql-check.test.ts)
//
// Rule (docs/REPORTS-DEV.md → Production SQL): a commit that adds or changes an apply-production-*.sql file also
// regenerates this check.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOCS_DIR = path.join(ROOT, 'docs', 'genie');
export const CHECK_FILE = path.join(DOCS_DIR, 'check-production-sql.sql');

// Data fixes that aren't schema changes, checked by their own query (UNION ALL rows: sql_file, status, found)
const EXTRA_ROWS = [
  `-- fix-production-early-completed-events.sql: "nothing to fix" means no event is left to put back
SELECT 'fix-production-early-completed-events.sql',
       CASE WHEN count(*) = 0 THEN 'nothing to fix' ELSE count(*) || ' event(s) still to put back' END,
       ''
FROM events
WHERE status = 'COMPLETED' AND ("eventDate" >= now() - interval '36 hours' OR "endTime" > now())`,
];

// [file, table, column | null (a whole table)] for every apply-production-*.sql, and the files with no schema change
export function expectedRows(dir = DOCS_DIR) {
  const files = fs.readdirSync(dir).filter(f => /^apply-production-.+\.sql$/.test(f)).sort();
  const rows = [];
  const skipped = [];
  for (const f of files) {
    const text = fs.readFileSync(path.join(dir, f), 'utf8').replace(/--.*$/gm, '');
    let lastTable = null;
    const found = [];
    for (const line of text.split('\n')) {
      let m = line.match(/ALTER TABLE\s+(?:IF EXISTS\s+)?"?(\w+)"?/i);
      if (m) lastTable = m[1];
      for (const c of line.matchAll(/ADD COLUMN\s+(?:IF NOT EXISTS\s+)?"?(\w+)"?/gi)) if (lastTable) found.push([lastTable, c[1]]);
      m = line.match(/CREATE TABLE\s+(?:IF NOT EXISTS\s+)?"?(\w+)"?/i);
      if (m) found.push([m[1], null]);
    }
    const uniq = [...new Map(found.map(r => [r.join('.'), r])).values()];
    if (uniq.length === 0) skipped.push(f);
    for (const [t, c] of uniq) rows.push([f, t, c]);
  }
  return { files, rows, skipped };
}

export function buildCheck(dir = DOCS_DIR) {
  const { rows, skipped } = expectedRows(dir);
  const q = s => (s === null ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
  const values = rows.map(([f, t, c]) => `  (${q(f)}, ${q(t)}, ${q(c)})`).join(',\n');
  return `-- Which docs/genie/apply-production-*.sql files have been run? READ-ONLY: changes nothing.
-- GENERATED by scripts/genie-sql-check.mjs: don't edit by hand; run \`node scripts/genie-sql-check.mjs\` after adding an
-- apply-production-*.sql file (tests/genie/sql-check.test.ts fails while this file is out of date).
-- Paste into the Neon SQL Editor on the PRODUCTION branch and press Run.
-- One row per file: applied / NOT RUN / PARTIAL, not-run files first. Run any NOT RUN or PARTIAL file (each is safe to re-run).
-- Files with no table or column changes, not listed: ${skipped.join(', ') || 'none'}.
WITH expected(sql_file, tbl, col) AS (VALUES
${values}
),
checked AS (
  SELECT e.*,
         CASE WHEN e.col IS NULL
              THEN EXISTS (SELECT 1 FROM information_schema.tables t WHERE t.table_schema = 'public' AND t.table_name = e.tbl)
              ELSE EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = e.tbl AND c.column_name = e.col)
         END AS found
  FROM expected e
),
per_file AS (
  SELECT sql_file,
         CASE WHEN count(*) FILTER (WHERE found) = count(*) THEN 'applied'
              WHEN count(*) FILTER (WHERE found) = 0 THEN 'NOT RUN'
              ELSE 'PARTIAL' END AS status,
         count(*) FILTER (WHERE found) || ' of ' || count(*) AS found
  FROM checked
  GROUP BY sql_file
)
SELECT * FROM (
  SELECT sql_file, status, found FROM per_file
  UNION ALL
${EXTRA_ROWS.map(r => r.replace(/^/gm, '  ')).join('\n  UNION ALL\n')}
) report
ORDER BY CASE WHEN status IN ('applied', 'nothing to fix') THEN 1 ELSE 0 END, sql_file;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = buildCheck();
  const { files, rows, skipped } = expectedRows();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(CHECK_FILE) ? fs.readFileSync(CHECK_FILE, 'utf8') : '';
    if (current !== sql) { console.error('docs/genie/check-production-sql.sql is out of date: run node scripts/genie-sql-check.mjs'); process.exit(1); }
    console.log('check-production-sql.sql is up to date');
  } else {
    fs.writeFileSync(CHECK_FILE, sql);
    console.log(`Wrote docs/genie/check-production-sql.sql: ${files.length} files, ${rows.length} checks${skipped.length ? `; no schema changes: ${skipped.join(', ')}` : ''}`);
  }
}
